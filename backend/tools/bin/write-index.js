#!/usr/bin/env node
'use strict';

/**
 * Regenerate gov_replica/README.md from the projects on disk, so the index
 * cannot drift from what was actually measured.
 *
 *   node bin/write-index.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..', 'gov_replica');

function readJson(p, fallback) {
  try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return fallback; }
}

function collect() {
  const out = [];
  for (const cat of fs.readdirSync(ROOT, { withFileTypes: true })) {
    if (!cat.isDirectory()) continue;
    const catDir = path.join(ROOT, cat.name);
    for (const proj of fs.readdirSync(catDir, { withFileTypes: true })) {
      if (!proj.isDirectory()) continue;
      const dir = path.join(catDir, proj.name);
      const o = readJson(path.join(dir, 'analysis', 'website_overview.json'), null);
      if (!o) continue;
      const tests = readJson(path.join(dir, 'tests', 'test-report.json'), null);
      const visual = readJson(path.join(dir, 'analysis', 'visual_comparison.json'), null);
      const site = readJson(path.join(dir, 'replica', 'backend', 'site.json'), null);
      const forms = readJson(path.join(dir, 'analysis', 'forms_and_interactions.json'), { counts: {} });
      out.push({
        category: cat.name,
        project: proj.name,
        hostname: o.hostname,
        pages: o.counts.pagesCaptured,
        exhausted: o.coverage.queueExhausted,
        pending: o.counts.pagesStillPending || 0,
        forms: forms.counts.forms || 0,
        fields: forms.counts.totalFunctionalFields || 0,
        assets: o.counts.assetsDownloaded,
        tests: tests ? tests.totals : null,
        visual: visual && visual.desktopDifferenceRatio ? visual.desktopDifferenceRatio.mean : null,
        port: site ? site.port : null,
        handTuned: !site,   // no generated site.json means it was built by hand
      });
    }
  }
  return out.sort((a, b) => a.category.localeCompare(b.category));
}

function main() {
  const rows = collect();
  const L = [];
  const P = (s) => L.push(s);

  P('# gov_replica');
  P('');
  P('Local demonstration replicas of public government portals, generated by the');
  P('pipeline in [`../tools`](../tools).');
  P('');
  P('Each replica is an **unofficial local demonstration** built for authorized');
  P('development, testing and educational use. None of these directories contains an');
  P('official government service, and none of them should be deployed anywhere a');
  P('member of the public could mistake it for one.');
  P('');
  P('## Why this exists');
  P('');
  P('The ERP described in `docs/requirements/erp-scope.pdf` has to exchange data with eight');
  P('external government systems. The research reports in `docs/research_reports/` establish that');
  P('**none of those systems publishes a public API** — every one is paper-based,');
  P('CAPTCHA-protected, or behind an authenticated login on a closed network. These');
  P('replicas therefore serve two purposes:');
  P('');
  P('1. a faithful reference for the fields, validation rules and workflows the ERP');
  P('   must mirror, so a citizen or officer never has to retype data; and');
  P('2. a local stand-in for integration development and testing, so ERP work does');
  P('   not depend on access to a production government system.');
  P('');
  P('## The replicas');
  P('');
  P('| Project | Host | Pages | Forms | Fields | Assets | Tests | Visual diff | Port |');
  P('|---|---|---|---|---|---|---|---|---|');
  for (const r of rows) {
    const cov = r.exhausted ? '' : ' \\*';
    const t = r.tests ? `**${r.tests.passed}/${r.tests.tests}**` : '—';
    P(`| [\`${r.category}/${r.project}\`](${r.category}/${r.project}/) | \`${r.hostname}\` | ` +
      `${r.pages}${cov} | ${r.forms} | ${r.fields} | ${r.assets} | ${t} | ` +
      `${r.visual == null ? '—' : r.visual} | ${r.port || '—'} |`);
  }
  P('');
  const truncated = rows.filter((r) => !r.exhausted);
  if (truncated.length) {
    P(`\\* the crawl stopped at the configured page limit, so ${truncated.length === 1 ? 'that site is' : 'those sites are'} ` +
      '**not fully explored** — ' +
      truncated.map((r) => `\`${r.hostname}\` has ${r.pending} in-scope URL(s) still queued`).join(', ') +
      '. Each project\'s `website_overview.json` states this exactly.');
    P('');
  }
  P('**Visual diff** is the measured mean pixel difference at desktop, banner-aligned');
  P('(see each project\'s `analysis/visual_comparison.json`). Lower is closer.');
  P('');
  const hand = rows.filter((r) => r.handTuned).map((r) => `\`${r.project}\``);
  if (hand.length) {
    P(`${hand.join(', ')} ${hand.length === 1 ? 'was' : 'were'} hand-tuned page by page.`);
  }
  P('The rest are generated by `tools/bin/build-replica.js` from the captured');
  P('analysis. The generator reproduces **fields, option lists, validation rules,');
  P('dependent dropdowns and page structure** faithfully, and approximates visual');
  P('design from measured colour, type and geometry tokens. It does not redistribute');
  P("the originals' illustrations, icons or prose, so on a heavily designed page a");
  P('high difference number means the replica looks different **on purpose** — not');
  P('that a pixel copy failed.');
  P('');
  P('## Category structure');
  P('');
  P('| Directory | Website category |');
  P('|---|---|');
  P('| `Aadhaar/` | Aadhaar/UIDAI identity services, enrolment, updates and related official services |');
  P('| `CCTNS/` | Crime and Criminal Tracking Network & Systems, police crime-record workflows and related portals |');
  P('| `E_Courts/` | eCourts, case status, court listings, cause lists, orders, judgments and court services |');
  P('| `E_Forensics/` | Government forensic services, forensic laboratories, forensic case management and evidence workflows |');
  P('| `E_Prisons/` | ePrisons, prison/jail administration, inmate management, visitor services and related portals |');
  P('');
  P('A site that fits none of these gets its own clearly named category directory, or');
  P('`Unclassified/` when the evidence does not support a confident verdict. Within a');
  P('category, every hostname gets its own isolated project directory. Artifacts for');
  P('one domain never leave that domain\'s directory.');
  P('');
  P('## Running one');
  P('');
  P('```bash');
  P('cd gov_replica/<Category>/<host>/replica/backend');
  P('npm install && npm run seed && npm start');
  P('```');
  P('');
  P('Then the tests:');
  P('');
  P('```bash');
  P('cd gov_replica/<Category>/<host> && node tests/run-tests.js');
  P('```');
  P('');
  P('Each project has its own `README.md` with the full picture: how it was analysed,');
  P('what could not be reached, how to run it, and what is deliberately not reproduced.');
  P('');
  P('## Adding another');
  P('');
  P('```bash');
  P('cd tools');
  P('node bin/gov-replica.js <domain>          # the domain is the only input');
  P('node bin/build-replica.js ../gov_replica/<Category>/<host> --port <N>');
  P('node bin/compare-replica.js ../gov_replica/<Category>/<host> http://127.0.0.1:<N>');
  P('node bin/write-readme.js ../gov_replica/<Category>/<host>');
  P('node bin/write-index.js                   # refresh this file');
  P('```');

  const out = L.join('\n') + '\n';
  fs.writeFileSync(path.join(ROOT, 'README.md'), out);
  process.stdout.write(`wrote gov_replica/README.md (${rows.length} projects, ${(out.length / 1024).toFixed(1)} KB)\n`);
  for (const r of rows) {
    process.stdout.write(`  ${r.category.padEnd(13)} ${r.hostname.padEnd(42)} ` +
      `${String(r.pages).padStart(4)}p  ${r.tests ? `${r.tests.passed}/${r.tests.tests}` : '—'}\n`);
  }
}

if (require.main === module) main();
module.exports = { collect };
