function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}

/** Snapshot the existing tree so we can prove nothing unrelated was touched. */
function inspectWorkspace() {
  const existing = { replicaRootExists: fs.existsSync(replicaRoot), categories: {} };
  if (!existing.replicaRootExists) return existing;
  for (const entry of fs.readdirSync(replicaRoot, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const catPath = path.join(replicaRoot, entry.name);
    const projects = fs.readdirSync(catPath, { withFileTypes: true })
      .filter((e) => e.isDirectory())
      .map((e) => e.name);
    const strayFiles = fs.readdirSync(catPath, { withFileTypes: true })
      .filter((e) => e.isFile())
      .map((e) => e.name);
    existing.categories[entry.name] = { projects, strayFiles };
  }
  return existing;
}

function initProject({ category, normalizedHostname }) {
  ensureDir(replicaRoot);

  const rootReadme = path.join(replicaRoot, 'README.md');
  if (!fs.existsSync(rootReadme)) {
    fs.writeFileSync(rootReadme, ROOT_README);
  }

  const categoryDir = path.join(replicaRoot, category);
  ensureDir(categoryDir);

  const projectDir = path.join(categoryDir, normalizedHostname);
  const resumed = fs.existsSync(projectDir);
  ensureDir(projectDir);
  for (const sub of SUBDIRS) ensureDir(path.join(projectDir, sub));

  return { projectDir, categoryDir, resumed, createdRootReadme: !fs.existsSync(rootReadme) };
}

/**
 * Write JSON without ever destroying a differing previous version: the old file
 * is kept alongside with a timestamp suffix (spec section 4: "never overwrite
 * existing user work wholesale").
 */
function writeJson(projectDir, relPath, data) {
  const full = path.join(projectDir, relPath);
  ensureDir(path.dirname(full));
  const next = JSON.stringify(data, null, 2) + '\n';
  if (fs.existsSync(full)) {
    const prev = fs.readFileSync(full, 'utf8');
    if (prev === next) return { path: full, changed: false };
    const stamp = new Date().toISOString().replace(/[:.]/g, '-');
    const backup = full.replace(/\.json$/, `.${stamp}.prev.json`);
    fs.writeFileSync(backup, prev);
    fs.writeFileSync(full, next);
    return { path: full, changed: true, backup };
  }
  fs.writeFileSync(full, next);
  return { path: full, changed: true };
}

function readJson(projectDir, relPath, fallback = null) {
  const full = path.join(projectDir, relPath);
  if (!fs.existsSync(full)) return fallback;
  try {
    return JSON.parse(fs.readFileSync(full, 'utf8'));
  } catch {
    return fallback;
  }
}

/** Append-only run log. */
function makeLogger(projectDir, runId) {
  const logDir = path.join(projectDir, 'logs');
  ensureDir(logDir);
  const file = path.join(logDir, `run-${runId}.log`);
  const stream = fs.createWriteStream(file, { flags: 'a' });
  const write = (level, stage, msg, extra) => {
    const line = JSON.stringify({
      ts: new Date().toISOString(), level, stage, msg,
      ...(extra ? { extra } : {}),
    });
    stream.write(line + '\n');
    if (level === 'error') process.stderr.write(`  [${stage}] ${msg}\n`);
  };
  return {
    file,
    info: (stage, msg, extra) => write('info', stage, msg, extra),
    warn: (stage, msg, extra) => write('warn', stage, msg, extra),
    error: (stage, msg, extra) => write('error', stage, msg, extra),
    close: () => new Promise((res) => stream.end(res)),
  };
}

module.exports = { inspectWorkspace, initProject, writeJson, readJson, makeLogger, ensureDir, SUBDIRS };
