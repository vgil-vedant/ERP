#!/usr/bin/env node
'use strict';

/**
 * Turns the images captured from eforensics.gov.in into base64 data URIs and
 * writes one EJS partial per image into the replica's views:
 *
 *   frontend/portals/eforensics/views/partials/img/<name>.ejs
 *
 * A view then places an image where the original put it:
 *
 *   <%- include('../partials/img/logo', { cls: 'brand__logo' }) %>
 *
 * Nothing is fetched from anywhere; the source is the capture already on disk
 * (backend/gov_replica/E_Forensics/eforensics_gov_in/original_assets/images).
 * Re-run after changing the table below:
 *
 *   node backend/scripts/embed-eforensics-images.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const SRC = path.join(ROOT, 'backend', 'gov_replica', 'E_Forensics', 'eforensics_gov_in', 'original_assets', 'images');
const OUT = path.join(ROOT, 'frontend', 'portals', 'eforensics', 'views', 'partials', 'img');

// partial name <- captured file, with the alt text for that place.
// An empty alt marks a decorative icon that sits next to its own text.
const IMAGES = [
  ['logo',                 'logo.png',                 'e-Forensic logo'],
  ['banner',               'Banner.png',               'Illustration: forensic scientist at a microscope with case, court and police icons'],
  ['key-feature-1',        'key-feature1.png',         ''],
  ['key-feature-2',        'key-feature2.png',         ''],
  ['key-feature-3',        'key-feature3.png',         ''],
  ['step-login',           'Login.png',                ''],
  ['step-registration',    'Registration.png',         ''],
  ['step-report-submission', 'Report-Submission.png',  ''],
  ['step-analyze-track',    'Analyze-Track.png',        ''],
  ['step-monitor-dashboard', 'Monitor-via-Dashboard.png', ''],
  ['phone',                'phone.png',                ''],
  ['email',                'email.png',                ''],
  ['location',             'location.png',             ''],
  ['nic-logo',             'nic_logo.png',             'NIC logo'],
];

function pngSize(buf) {
  if (buf.toString('latin1', 1, 4) !== 'PNG') throw new Error('not a PNG');
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
}

fs.mkdirSync(OUT, { recursive: true });
let total = 0;
for (const [name, file, alt] of IMAGES) {
  const buf = fs.readFileSync(path.join(SRC, file));
  const { w, h } = pngSize(buf);
  const b64 = buf.toString('base64');
  const body =
    `<%# generated by backend/scripts/embed-eforensics-images.js from original_assets/images/${file} %>` +
    `<img class="<%= typeof cls !== 'undefined' ? cls : '' %>" src="data:image/png;base64,${b64}" ` +
    `alt="${alt}" width="${w}" height="${h}">`;
  fs.writeFileSync(path.join(OUT, `${name}.ejs`), body);
  total += body.length;
  process.stdout.write(`${name.padEnd(24)} ${file.padEnd(26)} ${String(w).padStart(3)}x${String(h).padEnd(3)} ${String(buf.length).padStart(7)} B -> ${String(b64.length).padStart(7)} B base64\n`);
}
process.stdout.write(`${IMAGES.length} partials, ${(total / 1024).toFixed(0)} KB, written to ${path.relative(ROOT, OUT)}\n`);
