#!/usr/bin/env node
'use strict';

/**
 * Turns the images supplied in info/images/eprisoner.zip (extracted to
 * info/images/eprisoner/) and the dashboard icons beside it into base64 data URIs and writes one EJS partial per
 * image into the e-Prisons replica's views:
 *
 *   frontend/portals/eprisons/views/partials/img/<name>.ejs
 *
 * A view places an image where the original put it:
 *
 *   <%- include('../partials/img/feature-1') %>
 *
 * Each file's type is read from its own first bytes, not its extension, and
 * anything that is not a PNG or JPEG is refused. Nothing is executed or fetched.
 *
 *   node backend/scripts/embed-eprisons-images.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const SRC = path.join(ROOT, 'info', 'images');   // the zip's folder (eprisoner/) and the files beside it
const OUT = path.join(ROOT, 'frontend', 'portals', 'eprisons', 'views', 'partials', 'img');
const MAX_BYTES = 1024 * 1024;

// partial name <- supplied file, the alt text for that place ('' = decorative icon beside its own text)
const IMAGES = [
  ['logo',           'eprisoner/topleft.png',    'National Prisons Information Portal'],
  ['banner-digital', 'eprisoner/digital.jpg',    'Digital innovation in correctional homes. Visit booking made easy. Nation wide integrated information about inmates. Support inmates: legal aid portal, kiosk information.'],
  ['banner-services','eprisoner/ourservice.jpg', 'Our Services: Citizen Services, eMulakat, eCustody Certificate, Legal Aid, Grievance and eParole'],
  ['feature-1',      'eprisoner/feture1.png',    ''],   // Instant Visit Request
  ['feature-2',      'eprisoner/feature2.png',   ''],   // Dashboard Reports
  ['feature-3',      'eprisoner/feature3.png',   ''],   // ePrison Canteen
  ['feature-4',      'eprisoner/feature4.png',   ''],   // KIOSK Information
  ['feature-5',      'eprisoner/feature5.png',   ''],   // Grievances
  ['feature-6',      'eprisoner/feature6.png',   ''],   // Legal Aid
  ['tile-states',    'eprisoner/indiamap.png',   ''],   // States Covered
  ['tile-prisons',   'eprisoner/net.png',        ''],   // Prisons On-Board
  ['tile-records',   'eprisoner/comminity.png',  ''],   // Records held
  ['kpi-inside',     'dashboard.png',  ''],   // Dashboard card: Inmates inside
  ['kpi-admissions', 'dashboard2.png', ''],   // Dashboard card: Admissions today
  ['kpi-released',   'dashboard3.png', ''],   // Dashboard card: Released today
  ['kpi-visits',     'dashboard4.png', ''],   // Dashboard card: Visits registered today
  ['kpi-hearing',    'dashboard5.png', ''],   // Dashboard card: Court Hearing today
];

function inspect(buf, file) {
  if (buf.length >= 24 && buf.toString('latin1', 1, 4) === 'PNG' && buf[0] === 0x89) {
    return { mime: 'image/png', w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
  }
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2;
    while (i + 9 < buf.length) {
      if (buf[i] !== 0xff) { i += 1; continue; }
      const marker = buf[i + 1];
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
        return { mime: 'image/jpeg', h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
      }
      i += 2 + buf.readUInt16BE(i + 2);
    }
  }
  throw new Error(`${file} is not a PNG or JPEG`);
}

fs.mkdirSync(OUT, { recursive: true });
let total = 0;
for (const [name, file, alt] of IMAGES) {
  const buf = fs.readFileSync(path.join(SRC, file));
  if (buf.length > MAX_BYTES) throw new Error(`${file} is larger than ${MAX_BYTES} bytes`);
  const { mime, w, h } = inspect(buf, file);
  const b64 = buf.toString('base64');
  const safeAlt = alt.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
  const body =
    `<%# generated by backend/scripts/embed-eprisons-images.js from info/images/${file} %>` +
    `<img class="<%= typeof cls !== 'undefined' ? cls : '' %>" src="data:${mime};base64,${b64}" ` +
    `alt="${safeAlt}" width="${w}" height="${h}">`;
  fs.writeFileSync(path.join(OUT, `${name}.ejs`), body);
  total += body.length;
  process.stdout.write(`${name.padEnd(16)} ${file.padEnd(14)} ${mime.padEnd(10)} ${String(w).padStart(4)}x${String(h).padEnd(4)} ${String(buf.length).padStart(7)} B -> ${String(b64.length).padStart(7)} B base64\n`);
}
process.stdout.write(`${IMAGES.length} partials, ${(total / 1024).toFixed(0)} KB, written to ${path.relative(ROOT, OUT)}\n`);
